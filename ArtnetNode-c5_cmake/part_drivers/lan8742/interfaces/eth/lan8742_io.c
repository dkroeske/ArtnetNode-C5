/**
  * @brief  Enables the IRQ line and starts the EXTI.
  * @param  [in] pio : Pointer to io interface object
  * @retval error status
  */
int32_t lan8742_io_enable_irq(lan8742_io_t *pio)
{
  hal_exti_handle_t *p_exti = pio->hexti;
  /* Clear interrupt pending bit */
  HAL_EXTI_ClearPending(p_exti, HAL_EXTI_TRIGGER_RISING_FALLING);

  /* Enable NVIC interrupt request for the selected EXTI line.*/
  HAL_CORTEX_NVIC_EnableIRQ(pio->irq_src);

  /* Start the selected EXTI line on Interrupt Mode. */
  if (HAL_EXTI_Enable(p_exti, HAL_EXTI_MODE_INTERRUPT) != HAL_OK)
  {
    return -1;
  }
  return 0;
}

/**
  * @brief  Disables the IRQ line and clears the interrupt pending bit.
  * @param  [in] pio   Pointer to io interface object
  * @retval error status
  */
int32_t lan8742_io_disable_irq(lan8742_io_t *pio)
{
  /* Stop the selected EXTI line */
  if (HAL_EXTI_Disable(pio->hexti) != HAL_OK)
  {
    return -1;
  }
  /* Disable NVIC interrupt request for the selected EXTI line.*/
  HAL_CORTEX_NVIC_DisableIRQ(pio->irq_src);

  return 0;
}

#if defined (LAN8742_CALLBACKS) && (LAN8742_CALLBACKS == 1)

/**
  * @brief  Callback function for handling EXTI (External Interrupt) rising and falling edge triggers.
  * @param [in] p_exti   Pointer to the EXTI handle structure.
  * @param [in] trigger  Specifies the EXTI trigger event (rising, falling, both, or none).
  */
static void lan8742_exti_callback(hal_exti_handle_t *p_exti, hal_exti_trigger_t trigger)
{
  lan8742_io_t *pio = (lan8742_io_t *)HAL_EXTI_GetUserData(p_exti);
  hal_exti_trigger_t effective_trigger = trigger;

  if ((pio == NULL) || (pio->exti_cb_ctx.io_callback == NULL))
  {
    return;
  }

  /* Filter the event based on the trigger value.
   * When trigger information is insufficient, read the pin state as a workaround to infer edge direction.
   * (Reference: button part driver EXTI callback handling.)
   */
  if (effective_trigger == HAL_EXTI_TRIGGER_RISING_FALLING)
  {
    if (pio->it_pin != LAN8742_INVALID_PIN)
    {
      if (HAL_GPIO_ReadPin(pio->it_port, pio->it_pin) == HAL_GPIO_PIN_SET)
      {
        effective_trigger = HAL_EXTI_TRIGGER_RISING;
      }
      else
      {
        effective_trigger = HAL_EXTI_TRIGGER_FALLING;
      }
    }
  }

  if ((effective_trigger != HAL_EXTI_TRIGGER_RISING) && (effective_trigger != HAL_EXTI_TRIGGER_FALLING))
  {
    return;
  }

  if (effective_trigger == HAL_EXTI_TRIGGER_FALLING)
  {
    pio->exti_cb_ctx.io_callback(pio, pio->exti_cb_ctx.arg);
  }
  else
  {
    /* Ignore rising pin events */
  }
}

/**
  * @brief Registers a callback on the IT pin of the LAN8742.
  * @param  [in,out] pio   : Pointer to io interface object
  * @param  [in] io_cb : Callback function to be registered
  * @param  [in] arg   : Optional argument given to the callback
  * @retval error status (0=success, -1=error)
  */
int32_t lan8742_io_register_callback(lan8742_io_t *pio, lan8742_io_callback_t io_cb, void *arg)
{
  hal_exti_handle_t *p_exti = pio->hexti;

  pio->exti_cb_ctx.io_callback = io_cb;
  pio->exti_cb_ctx.arg = arg;
  HAL_EXTI_SetUserData(p_exti, pio);

  if (HAL_EXTI_RegisterTriggerCallback(p_exti, lan8742_exti_callback) != HAL_OK)
  {
    return -1;
  }
  return 0;
}

#endif /* LAN8742_CALLBACKS */
