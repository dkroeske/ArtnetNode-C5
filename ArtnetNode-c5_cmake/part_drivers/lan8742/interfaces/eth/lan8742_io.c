/**
  * @brief Initializes the hardware reset sequence for the LAN8742 Ethernet PHY.
  *
  * This function asserts and de-asserts the nRST (reset) pin of the LAN8742 PHY
  * according to the specified active state in the provided IO structure. If a valid
  * nRST pin is defined, the function will:
  *   - Set the nRST pin to its active state.
  *   - Wait for 10 milliseconds to ensure the reset is asserted.
  *   - Set the nRST pin to its inactive state.
  * If no valid nRST pin is defined, the function does nothing and only software reset
  * will be used for the PHY.
  *
  * @param pio [in] Pointer to the LAN8742 IO structure containing GPIO configuration.
  */
void lan8742_io_hw_reset(lan8742_io_t *pio)
{
  if (pio->nrst_pin != LAN8742_INVALID_PIN)
  {
    /* Hardware Init sequence */
    HAL_GPIO_WritePin(pio->nrst_port, pio->nrst_pin,
                      (((uint8_t)pio->nrst_active_state == (uint8_t)HAL_GPIO_PIN_RESET) ?
                       HAL_GPIO_PIN_RESET : HAL_GPIO_PIN_SET));
    HAL_Delay(1);   /* nRST signal asserted during 100us */

    HAL_GPIO_WritePin(pio->nrst_port, pio->nrst_pin,
                      (((uint8_t)pio->nrst_active_state == (uint8_t)HAL_GPIO_PIN_SET) ?
                       HAL_GPIO_PIN_RESET : HAL_GPIO_PIN_SET));
  }
  else
  {
    /* No GPIO defined for nRST signal, only software reset will be used */
  }
}

